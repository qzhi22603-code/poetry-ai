# ==============================================================================
# 【本文件在管线中的作用】
#   这是 poemly 训练管线的"意象词典 + 模板库"，属于数据工程的"弹药库"：
#   它自己不产出训练样本，只提供三类原料，供数据生成器 scale_generator.py
#   通过 from imagery import ... 导入使用——
#     1) IMAGERY：意象字 -> 意蕴短语列表 的映射表。生成器拿着它去诗句里"抓"意象，
#        抓到后随机抽一条意蕴，套进解释模板拼出"意象解释"这种训练目标文本。
#     2) LINE_PATTERNS / ROLE_JUE / ROLE_LV / ADJ：解释句的句式模板、章法角色表
#        （起承转合/四联）、风格形容词池——让机器生成的解释读起来像人写的诗话。
#     3) LIYI_PLAIN / EMO_BY_KEY / EMO_DEFAULT / INSTR_TPL：生成"立意句"和
#        "作诗指令"的模板池，对应 SFT 样本 output 开头的"立意："段与 instruction 字段。
#   本文件几乎全是数据字面量（类似 C 里的 static const 配置表），import 时执行
#   一次即建表常驻内存，之后供下游 O(1) 查表。
#
# 【Python 特性速查（C 语言视角）】
#   - dict（字典）≈ 哈希表：IMAGERY 就是"键=意象字，值=字符串数组"的哈希表，
#     约等于 C 里 struct { const char* key; char** meanings; } 的数组 + O(1) 查找。
#   - list（列表）≈ 自动扩容的动态数组（char**），用方括号字面量直接初始化。
#   - 字符串是内建不可变对象，无需 \0 结尾、长度自带，可直接装中文；
#     {xxx} 占位符由 str.format(...) 按名替换，功能 ≈ sprintf。
#   - 字典同键后写覆盖先写（哈希表语义）：本文件"笛"出现两次，最终只保留最后一条。
#   - 值的类型允许不齐（有的是 list 有的是 str），靠 isinstance 在下游做运行时判断
#     兼容——这是动态类型语言与 C 的关键差异。
#
# 【执行前提】
#   - 无第三方依赖，纯数据文件；以 UTF-8 编码保存。
#   - 需与 scale_generator.py 同目录（或在其 sys.path 上），供其 import。
